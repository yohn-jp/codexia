import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { assertVerificationLeafJobs, collectGitHubPages } from './release-policy.mjs';
const { GITHUB_REPOSITORY: repository, GITHUB_RUN_ID: runId, GH_TOKEN: token, CODEXIA_EXPECTED_SHA: sha } = process.env;
assert.match(repository ?? '', /^[\w.-]+\/[\w.-]+$/);
assert.match(runId ?? '', /^\d+$/);
assert.match(sha ?? '', /^[a-f0-9]{40}$/);
assert.ok(token);
assert.equal(execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(), sha);
const request = async endpoint => {
  const response = await fetch(`https://api.github.com/repos/${repository}/${endpoint}`, { headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json' }, signal: AbortSignal.timeout(15_000), redirect: 'error' });
  assert.ok(response.ok, `Verification evidence unavailable (${response.status})`);
  return response.json();
};
const run = await request(`actions/runs/${runId}`);
assert.equal(run.head_sha, sha);
const jobs = await collectGitHubPages(page => request(`actions/runs/${runId}/jobs?filter=latest&per_page=100&page=${page}`), 'jobs');
const leaves = jobs.filter(job => job.name !== 'certification');
for (const job of leaves) assert.equal(job.head_sha, sha);
assertVerificationLeafJobs(leaves);
console.log(`Certified all PostgreSQL validations at ${sha}, run ${runId}`);

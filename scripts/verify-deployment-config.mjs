import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const read = file => readFile(new URL(`../${file}`, import.meta.url), 'utf8');
const routes = JSON.parse(await read('deploy/cloudflare/ui-routes.json'));
assert.deepEqual(routes.routes, ['/', '/index.html*', '/assets/*', '/desktop*', '/mobile*']);
const worker = JSON.parse(await read('edge/frontend/wrangler.jsonc'));
assert.equal(worker.workers_dev, false);
assert.equal(worker.preview_urls, false);
assert.equal(worker.assets.not_found_handling, 'none');
assert.equal(worker.assets.directory, '../../app/dist');
assert.ok(!worker.assets.run_worker_first.includes('/r/*'));
const source = await read('edge/frontend/src/index.ts');
assert.ok(source.includes('env.ASSETS.fetch'));
assert.doesNotMatch(source, /(?<!ASSETS\.)fetch\(request\)/u);
const frontend = await read('.github/workflows/frontend-release.yml');
assert.ok(frontend.includes('secrets.CLOUDFLARE_ACCOUNT_ID'));
assert.ok(frontend.includes('secrets.CLOUDFLARE_API_TOKEN'));
assert.ok(!frontend.includes('vars.CLOUDFLARE_ACCOUNT_ID'));
const quadlet = await read('deploy/quadlet/codexia-api.container');
assert.match(quadlet, /Requires=codexia-db.service/u);
assert.match(quadlet, /CODEXIA_DATABASE_PASSWORD_FILE=/u);
assert.doesNotMatch(quadlet, /GITHUB_TOKEN|PROFILE|^PublishPort=/mu);
assert.match(await read('deploy/cloudflare/terraform/main.tf'), /required\s+=\s+true/u);
assert.doesNotMatch(await read('Dockerfile.backend'), /ca-certificates git|module-runtime|profile-package/u);
console.log('PostgreSQL deployment, narrow routes and production secrets verified.');

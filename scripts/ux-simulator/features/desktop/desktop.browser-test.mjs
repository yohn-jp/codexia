import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { extname, join, resolve, sep } from 'node:path';
import { generate } from '../../generate.mjs';

const [playwright, executablePath] = process.argv.slice(2);
assert.ok(playwright && executablePath, 'Usage: desktop.browser-test.mjs PLAYWRIGHT_CORE CHROMIUM');
const { chromium } = createRequire(import.meta.url)(resolve(playwright));
const output = await mkdtemp(join(tmpdir(), 'codexia-ux-desktop-'));
const mime = { '.html': 'text/html', '.mjs': 'text/javascript', '.css': 'text/css', '.json': 'application/json' };
const server = createServer(async (request, response) => {
  try {
    const { pathname } = new URL(request.url, 'http://localhost');
    const file = resolve(output, '.' + (pathname === '/' ? '/index.html' : pathname));
    assert.ok(file.startsWith(output + sep));
    response.writeHead(200, { 'content-type': mime[extname(file)] }).end(await readFile(file));
  } catch {
    response.writeHead(404).end();
  }
});


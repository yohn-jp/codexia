import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readFile } from 'node:fs/promises';
import { generateKeyPairSync } from 'node:crypto';
import { nextChannel, nextChannelWithRegistry, releaseFromIdentity } from './publish-stable-channel.mjs';
import { selectUpdateCandidate, signUpdateChannel, verifyUpdateChannel, authenticateHistoricalChannel } from './update-channel.mjs';
import { initialStableChannelRegistry, nextStableChannelRegistry, signStableChannelRegistry, verifyStableChannelRegistry } from './stable-channel-registry.mjs';
const now=Date.parse('2026-11-12T12:00:00.000Z');
const hash=c=>'sha256:'+c.repeat(64);
const image=c=>'ghcr.io/yohn-jp/codexia-backend@'+hash(c);
const release=(v,c)=>({format:'codexia-update-release/v1',channel:'stable',state:'published',version:v,sourceSha:c.repeat(40),image:image(c),platform:'linux/amd64',profile:'core',migrationFingerprint:hash('e'),persistenceFormat:1,apiEpoch:1});
test('credentialed stable publisher inspects image identity without starting image code',async()=>{
  const source=await readFile(new URL('./publish-stable-channel.mjs',import.meta.url),'utf8');
  assert.match(source,/output\(\['create','--entrypoint','\/bin\/false',image\]\)/u);
  assert.ok(source.includes("output(['cp',container+':/app/update-identity.json',identityPath])"));
  assert.doesNotMatch(source,/output\(\['run'/u);
});
test('bootstrap, monotonic publish, refresh and withdrawal preserve immutable identities',()=>{
  const zero=nextChannel(null,{mode:'bootstrap'},now);
  assert.equal(zero.sequence,1);
  assert.throws(()=>nextChannel(zero,{mode:'bootstrap'},now));
  assert.throws(()=>nextChannel(null,{mode:'publish',release:release('0.1.0','a')},now));
  const one=nextChannel(zero,{mode:'publish',release:release('0.1.0','a')},now);
  assert.equal(one.sequence,2);
  assert.throws(()=>nextChannel(one,{mode:'publish',release:release('0.1.0','b')},now),/different artifact/);
  assert.equal(nextChannel(one,{mode:'publish',release:release('0.1.0','a')},now),null);
  const two=nextChannel(one,{mode:'publish',release:release('0.1.1','b')},now);
  assert.throws(()=>nextChannel(two,{mode:'publish',release:release('0.0.1','c')},now));
  const withdrawn=nextChannel(two,{mode:'withdraw',image:image('b')},now);
  assert.equal(withdrawn.releases[1].state,'withdrawn');
  assert.throws(()=>nextChannel(withdrawn,{mode:'publish',release:release('0.1.1','b')},now));
  assert.throws(()=>nextChannel(withdrawn,{mode:'publish',release:release('0.1.2','b')},now));
  assert.equal(nextChannel(withdrawn,{mode:'refresh'},now+1000).sequence,withdrawn.sequence+1);
});
test('expired historic payload is usable only by publisher, never a current host channel',()=>{
  const {publicKey,privateKey}=generateKeyPairSync('ed25519');
  const pub=publicKey.export({type:'spki',format:'pem'}),priv=privateKey.export({type:'pkcs8',format:'pem'});
  const state=nextChannel(null,{mode:'bootstrap'},now);
  const envelope=signUpdateChannel(state,priv,now);
  assert.throws(()=>verifyUpdateChannel(envelope,pub,null,now+13*60*60*1000),/expired/);
  assert.deepEqual(authenticateHistoricalChannel(envelope,pub),state);
  const other=generateKeyPairSync('ed25519').publicKey.export({type:'spki',format:'pem'});
  assert.throws(()=>authenticateHistoricalChannel(envelope,other),/signature/);
});
test('release identity must match certified source and compatibility',()=>{
  const r=release('0.1.0','a');
  const {format,channel,state,image:artifact,...fields}=r;
  const identity={format:'codexia-backend-identity/v1',...fields};
  const compatibility={apiEpoch:1,persistenceFormat:1};
  assert.deepEqual(releaseFromIdentity(identity,artifact,r.sourceSha,r.version,compatibility,'core'),r);
  assert.throws(()=>releaseFromIdentity(identity,artifact,'b'.repeat(40),r.version,compatibility,'core'));
  assert.throws(()=>releaseFromIdentity(identity,artifact,r.sourceSha,r.version,{...compatibility,apiEpoch:2},'core'));
});


test('certified Core and Full are advertised together without replacing an existing version',()=>{
  const core=release('0.1.0','a');
  const full={...core,profile:'full',image:image('b')};
  const zero=nextChannel(null,{mode:'bootstrap'},now);
  const both=nextChannel(zero,{mode:'publish',releases:[core,full]},now);
  assert.equal(both.sequence,2);
  assert.deepEqual(both.releases,[core,full]);
  assert.equal(nextChannel(both,{mode:'publish',releases:[core,full]},now),null);
  const old=nextChannel(zero,{mode:'publish',release:core},now);
  const added=nextChannel(old,{mode:'publish',releases:[core,full]},now);
  assert.deepEqual(added.releases,[core,full]);
  assert.throws(()=>nextChannel(zero,{mode:'publish',releases:[core,{...full,sourceSha:'c'.repeat(40)}]},now),/share source/);
  assert.throws(()=>nextChannel(zero,{mode:'publish',releases:[core,{...full,image:core.image}]},now),/distinct images/);
  assert.throws(()=>nextChannel(zero,{mode:'publish',releases:[core,core]},now),/Duplicate candidate profile/);
  const newer=release('0.1.1','c');
  const newerFull={...newer,profile:'full',image:image('d')};
  const next=nextChannel(both,{mode:'publish',releases:[newer,newerFull]},now);
  assert.deepEqual(next.releases,[core,full,newer,newerFull]);
  const withdrawn=nextChannel(next,{mode:'withdraw',image:newerFull.image},now);
  assert.throws(()=>nextChannel(withdrawn,{mode:'publish',releases:[newer,newerFull]},now),/Withdrawn version/);
});

test('stable channel rolls at the v1 count boundary and keeps signed history authoritative',()=>{
  const {publicKey,privateKey}=generateKeyPairSync('ed25519');
  const pub=publicKey.export({type:'spki',format:'pem'}),priv=privateKey.export({type:'pkcs8',format:'pem'});
  const initial=nextChannelWithRegistry(null,{mode:'bootstrap'},now);
  let channel=initial.channel,history=initial.history;
  let envelope=signUpdateChannel(channel,priv,now);
  let bytes=Buffer.from(JSON.stringify(envelope)+'\n');
  let registry=initialStableChannelRegistry(channel,bytes);
  let signedRegistry=signStableChannelRegistry(registry,priv,bytes);
  registry=verifyStableChannelRegistry(signedRegistry,pub,bytes);
  let checkpoint=verifyUpdateChannel(envelope,pub,null,now).checkpoint;
  for(let version=0;version<500;version++){
    const suffix=version.toString(16).padStart(40,'0');
    const next={...release(`0.1.${version+1}`,'a'),sourceSha:suffix,image:`ghcr.io/yohn-jp/codexia-backend@sha256:${suffix.padStart(64,'0')}`};
    const full={...next,profile:'full',image:`ghcr.io/yohn-jp/codexia-backend@sha256:${(version+500).toString(16).padStart(64,'0')}`};
    const result=nextChannelWithRegistry(channel,{mode:'publish',releases:[next,full]},now+version+1,registry);
    assert.ok(result);
    channel=result.channel;history=result.history;
    registry={...registry,releases:history};
  }
  assert.equal(channel.releases.length,1000);
  const finalVersion=release('0.1.501','f');
  const finalFull={...finalVersion,profile:'full',image:`ghcr.io/yohn-jp/codexia-backend@sha256:${'e'.repeat(64)}`};
  const boundary=nextChannelWithRegistry(channel,{mode:'publish',releases:[finalVersion,finalFull]},now+600,registry);
  assert.ok(boundary);
  assert.equal(boundary.channel.sequence,channel.sequence+1);
  assert.equal(boundary.channel.releases.length,1000);
  assert.ok(Buffer.byteLength(JSON.stringify(boundary.channel))<1024*1024);
  assert.ok(boundary.channel.releases.some(r=>r.version==='0.1.500'&&r.profile==='core'&&r.state==='published'));
  assert.ok(boundary.channel.releases.some(r=>r.version==='0.1.500'&&r.profile==='full'&&r.state==='published'));
  assert.equal(boundary.history.length,1002);
  const repeated=nextChannelWithRegistry(boundary.channel,{mode:'publish',releases:[finalVersion,finalFull]},now+601,{releases:boundary.history});
  assert.equal(repeated,null);
  const signed=signUpdateChannel(boundary.channel,priv,now+600);
  const channelBytes=Buffer.from(JSON.stringify(signed)+'\n');
  const nextRegistry=nextStableChannelRegistry(registry,boundary.channel,channelBytes,boundary.history);
  const signedHistory=signStableChannelRegistry(nextRegistry,priv,channelBytes);
  const verifiedHistory=verifyStableChannelRegistry(signedHistory,pub,channelBytes);
  assert.equal(verifiedHistory.channelSequence,boundary.channel.sequence);
  assert.equal(verifiedHistory.releases.length,1002);
  const after=verifyUpdateChannel(signed,pub,checkpoint,now+600);
  assert.equal(after.checkpoint.sequence,boundary.channel.sequence);
  const previousCore=boundary.history.find(r=>r.profile==='core'&&r.version==='0.1.500');
  const previousFull=boundary.history.find(r=>r.profile==='full'&&r.version==='0.1.500');
  assert.equal(selectUpdateCandidate(after,previousCore,1).image,finalVersion.image);
  assert.equal(selectUpdateCandidate(after,previousFull,1).image,finalFull.image);
  assert.equal(nextChannelWithRegistry(boundary.channel,{mode:'publish',release:boundary.history[0]},now+601,{releases:boundary.history}),null);
  checkpoint=after.checkpoint;
  assert.throws(()=>verifyUpdateChannel(envelope,pub,checkpoint,now+600),/rollback/);
  const archived=boundary.history[0];
  const withdrawnArchived=nextChannelWithRegistry(boundary.channel,{mode:'withdraw',image:archived.image},now+601,verifiedHistory);
  assert.equal(withdrawnArchived.history.find(r=>r.image===archived.image).state,'withdrawn');
  assert.ok(!withdrawnArchived.channel.releases.some(r=>r.image===archived.image));
  assert.throws(()=>nextChannelWithRegistry(withdrawnArchived.channel,{mode:'publish',release:archived},now+602,{releases:withdrawnArchived.history}),/Withdrawn version/);
  const withdrawn=nextChannelWithRegistry(boundary.channel,{mode:'withdraw',image:finalFull.image},now+602,verifiedHistory);
  assert.ok(withdrawn.channel.releases.some(r=>r.image===finalFull.image&&r.state==='withdrawn'));
  assert.equal(withdrawn.history.find(r=>r.image===finalFull.image).state,'withdrawn');
  assert.throws(()=>nextChannelWithRegistry(withdrawn.channel,{mode:'publish',releases:[finalVersion,finalFull]},now+603,{releases:withdrawn.history}),/Withdrawn version/);
  assert.throws(()=>verifyStableChannelRegistry(signedHistory,pub,Buffer.from('different')),/Invalid stable channel document|does not bind/);
});

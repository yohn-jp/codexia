// This expected inventory is intentionally independent of TypeSpec. It is the
// admitted main route surface transcribed from the Fastify dispatcher,
// persistence dispatcher, module contributions, Backup Console and auth adapters.
// Better Auth library routes remain
// external to this list and are generated by Better Auth itself.
function assertAdmittedRouteInventory(openapi) {
  const methods = new Set(['delete', 'get', 'head', 'options', 'patch', 'post', 'put', 'trace']);
  const operations = Object.entries(openapi.paths ?? {}).flatMap(([pathname, pathItem]) =>
    Object.entries(pathItem)
      .filter(([method]) => methods.has(method))
      .map(([method, operation]) => ({ key: `${method.toUpperCase()} ${pathname}`, operation })),
  );
  const actual = operations.map(({ key }) => key).sort();
  const expected = [...admittedInventory.current, ...admittedInventory.target].sort();
  const actualSet = new Set(actual);
  const expectedSet = new Set(expected);
  const missing = expected.filter(key => !actualSet.has(key));
  const unexpected = actual.filter(key => !expectedSet.has(key));
  if (missing.length || unexpected.length) {
    throw new Error(`Admitted route inventory mismatch: missing=[${missing.join(', ')}], unexpected=[${unexpected.join(', ')}]`);
  }
  if (actual.length !== expected.length) throw new Error('Admitted route inventory contains duplicate method/path entries');
  if (new Set(expected.map(key => key.slice(key.indexOf(' ') + 1))).size !== 90) {
    throw new Error('Admitted route inventory must contain exactly 90 path templates');
  }
  if (admittedInventory.current.length !== 115 || admittedInventory.target.length !== 0) {
    throw new Error('Admitted route inventory must contain 115 current routes and no target-only routes');
  }

  const targetSet = new Set(admittedInventory.target);
  for (const { key, operation } of operations) {
    const status = operation['x-codexia-contract-status'] ?? openapi['x-codexia-contract-status'];
    if (targetSet.has(key)) assert.equal(status, 'target', `${key} must remain a target operation`);
    else assert.notEqual(status, 'target', `${key} is current and must not be marked target`);
  }

  const betterAuth = openapi['x-codexia-external-contracts']?.betterAuth;
  assert.equal(betterAuth?.source, 'Better Auth official runtime OpenAPI generation');
  assert.equal(betterAuth?.pathPrefix, admittedInventory.betterAuthExternal.pathPrefix);
  assert.equal(betterAuth?.libraryOperationsIncludedHere, false);
  assert.deepEqual(betterAuth?.applicationAdaptersHere, admittedInventory.betterAuthAdapters);
  assert.deepEqual(openapi['x-codexia-external-contracts']?.betterAuthMetadataPaths, admittedInventory.betterAuthExternal.metadataPaths);
  assert.deepEqual(betterAuth?.setupOnlyOfficialLibraryPaths, admittedInventory.betterAuthExternal.excludedApplicationWrappers);
  for (const externalOperation of [
    ...admittedInventory.betterAuthExternal.excludedLibraryOperations,
    ...admittedInventory.betterAuthExternal.excludedApplicationWrappers,
  ]) {
    assert.ok(!actualSet.has(externalOperation), `${externalOperation} belongs to Better Auth's official external contract`);
  }
  for (const adapter of admittedInventory.betterAuthAdapters) assert.ok(actualSet.has(adapter), `${adapter} is Codexia-owned`);
  return actual;
}

function compile(outputDirectory) {
  execFileSync(
    compiler,
    [
      'compile',
      path.join(packageRoot, 'src', 'main.tsp'),
      '--output-dir',
      path.join(outputDirectory, 'compiler'),
      '--options',
      `@typespec/openapi3.emitter-output-dir=${path.join(outputDirectory, 'openapi')}`,
    ],
    { cwd: packageRoot, stdio: 'pipe' },
  );
  return path.join(outputDirectory, 'openapi', 'codexia.openapi.yaml');
}

test('TypeSpec emits deterministic OpenAPI 3.1 and explicit operation IDs', t => {
  const firstDirectory = mkdtempSync(path.join(tmpdir(), 'codexia-http-contract-a-'));
  const secondDirectory = mkdtempSync(path.join(tmpdir(), 'codexia-http-contract-b-'));
  t.after(() => {
    rmSync(firstDirectory, { recursive: true, force: true });
    rmSync(secondDirectory, { recursive: true, force: true });
  });

  const firstPath = compile(firstDirectory);
  const secondPath = compile(secondDirectory);
  const firstBytes = readFileSync(firstPath);
  const openapi = parse(firstBytes.toString('utf8'));

  assert.deepEqual(readFileSync(secondPath), firstBytes);
  assert.deepEqual(readFileSync(path.join(packageRoot, 'openapi', 'codexia.openapi.yaml')), firstBytes);
  assert.equal(openapi.openapi, '3.1.0');
  assert.equal(openapi.info.version, '2.0.0');
  const backendCompatibility = JSON.parse(readFileSync(new URL('../../../deploy/update-compatibility.json', import.meta.url), 'utf8'));
  const frontendCompatibility = JSON.parse(readFileSync(new URL('../../../deploy/frontend-compatibility.json', import.meta.url), 'utf8'));
  assert.equal(openapi['x-codexia-api-epoch'], backendCompatibility.apiEpoch);
  assert.equal(openapi['x-codexia-api-epoch'], frontendCompatibility.apiEpoch);
  assert.equal(openapi['x-codexia-cors'].credentials, false);
  assert.match(openapi['x-codexia-cors'].preflight.route, /explicit OPTIONS for registered API and MCP paths/u);
  assert.equal(openapi['x-codexia-cors'].preflight.successStatus, 204);
  assert.equal(openapi['x-codexia-cors'].preflight.deniedStatus, 403);
  assert.deepEqual(openapi['x-codexia-cors'].preflight.allowMethods, ['GET', 'HEAD', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS']);
  assert.match(openapi['x-codexia-cors'].originPolicy, /wildcard origins are forbidden/u);
  assert.deepEqual(openapi['x-codexia-cors'].mcpExposeHeaders, ['MCP-Protocol-Version', 'WWW-Authenticate']);
  assert.deepEqual(openapi['x-codexia-cors'].mcpRequestHeaders, ['MCP-Protocol-Version', 'Mcp-Method', 'Mcp-Name']);
  assert.equal(openapi['x-codexia-external-contracts'].betterAuth.libraryOperationsIncludedHere, false);
  assert.equal(openapi.paths['/api/auth/codexia/auth-methods'].get.operationId, 'auth_methods_get');
  assert.equal(openapi.paths['/api/auth/codexia/owner-session'].post.operationId, 'owner_session_confirm_post');
  assert.ok(!openapi.paths['/api/auth/sign-in/email']);
  assert.ok(openapi.paths['/api/auth/oauth2/consent-context'].post);
  assert.ok(openapi.paths['/api/auth/oauth2/get-consents'].get);
  assert.equal(openapi.paths['/api/health'].get.operationId, 'api_health_get');
  assert.ok(openapi.paths['/api/health'].get.responses['200']);
  assert.ok(openapi.paths['/api/health'].get.responses['503']);
  for (const route of [
    '/api/health',
    '/api/ready',
    '/health/live',
    '/health/ready',
    '/health/startup',
    '/api/version',
    '/api/browser/version',
  ]) {
    assert.ok(openapi.paths[route].get, `${route} GET remains declared`);
    assert.ok(openapi.paths[route].head, `${route} HEAD is explicitly declared`);
    for (const response of Object.values(openapi.paths[route].head.responses)) {
      assert.equal(response.content, undefined, `${route} HEAD must not declare a response body`);
      assert.equal(response.headers?.['content-type']?.schema?.enum?.[0], 'application/json');
    }
  }
  for (const route of ['/api/ready', '/health/ready', '/health/startup']) {
    const unavailable = openapi.paths[route].get.responses['503'];
    assert.ok(unavailable, `${route} GET must document the runtime unavailable status`);
    assert.equal(unavailable.headers['Cache-Control'].schema.enum[0], 'no-store');
    const schema = unavailable.content['application/json'].schema;
    if (route === '/health/ready') {
      assert.deepEqual(schema.anyOf.map(({ $ref }) => $ref).sort(), [
        '#/components/schemas/OwnerSetupReadinessUnavailableBody',
        '#/components/schemas/ReadinessResponse',
      ]);
      assert.equal(openapi.components.schemas.OwnerSetupReadinessUnavailableBody.properties.code.enum[0], 'SETUP_UNAVAILABLE');
      assert.equal(
        openapi.paths[route].get.responses['200'].content['application/json'].schema.$ref,
        '#/components/schemas/ReadinessResponse',
      );
      assert.equal(openapi.paths[route].get['x-codexia-contract-status'], 'incomplete');
      assert.match(openapi.paths[route].get['x-codexia-runtime-response-deviation'], /status: "ready"/u);
    } else {
      assert.equal(schema.$ref, '#/components/schemas/ReadinessResponse');
    }
  }
});

